# -*- coding: utf-8 -*-
"""Sky Lift reward tables: CSV (the sheet format, Unity reward ids) -> ../sky-lift-rewards.js for the web prototypes.
CSV columns: floor, chestId, rewardId1..4, rewardValue1..4, comment. Reward ids are the Unity ones (Coin, Booster1..5, PowerUp1..3);
GAMES maps them to the prototype booster keys. Run: python3 build_rewards.py  (writes deploy/events-kit/sky-lift-rewards.js)."""
import csv, json
from pathlib import Path
HERE = Path(__file__).resolve().parent
GAMES = {
  'bookshelf': {'csv': 'sky-lift-rewards-bookshelf.csv', 'ids': {'Booster1':'peek','Booster2':'lens','Booster3':'key','Booster4':'glove','Booster5':'brush','PowerUp1':'bookmark','PowerUp2':'corners','PowerUp3':'center'}},
  'sizematch': {'csv': 'sky-lift-rewards-sizematch.csv', 'ids': {'Booster1':'info','Booster2':'swap','Booster3':'jk','Booster4':'shield'}},
}
def reward(rid, val, ids):
    if rid == 'Coin': return {'type':'coins','n':int(val)}
    if rid == 'UnlimitedLives': return {'type':'lives','min':int(val)}
    if rid not in ids: raise SystemExit('unknown rewardId '+rid)
    return {'type':'booster','id':ids[rid],'n':int(val)}
out = {}
for game, g in GAMES.items():
    rows = list(csv.DictReader(open(HERE/g['csv'], encoding='utf-8')))
    ms, rs, chests = [], [], []
    for r in rows:
        f = int(r['floor']); assert not ms or f > ms[-1], ('floors must grow', f)
        items = [reward(r[f'rewardId{i}'], r[f'rewardValue{i}'], g['ids']) for i in range(1,5) if r.get(f'rewardId{i}')]
        assert items, ('empty chest', f)
        ms.append(f); rs.append(items[0] if len(items)==1 else items); chests.append(r['chestId'])
    assert chests[-1] == 'grand' and 'grand' not in chests[:-1], 'the last row is the grand prize'
    out[game] = {'milestones': ms, 'rewards': rs, 'chests': chests}
js = ('/* generated by config/build_rewards.py from config/sky-lift-rewards-*.csv (do not edit by hand) */\n'
      'window.SKY_LIFT_REWARDS=' + json.dumps(out, separators=(',',':'), ensure_ascii=False) + ';\n')
(HERE.parent/'sky-lift-rewards.js').write_text(js, encoding='utf-8')
for game, c in out.items(): print(game, len(c['milestones']), 'milestones, top', c['milestones'][-1])
